#!/usr/bin/env python3
"""gen_layout -- the shared shader/C++ layout (sub-project 2b spec, "Slang").

    python tools/gen_layout.py            write the two generated files from layout.json
    python tools/gen_layout.py --check    exit 1 (and name the files) if any is out of date

shaders/shared/layout.json -> shaders/shared/layout.slang (import shared.layout) and
ohao/gpu/shared_layout.hpp (namespace ohao::gpu::shared). Structs are laid out by std430's rules; the header gives each
field its std430 alignment and static_asserts every offset and the size, so a C++ struct
cannot drift from the shader's. Paths can be overridden (--layout/--slang/--hpp) for
tests.
"""
import argparse
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULTS = {
    "layout": os.path.join(ROOT, "shaders", "shared", "layout.json"),
    "slang": os.path.join(ROOT, "shaders", "shared", "layout.slang"),
    "hpp": os.path.join(ROOT, "ohao", "gpu", "shared_layout.hpp"),
}
HEADER = "Generated by tools/gen_layout.py from shaders/shared/layout.json. Do not edit."

# type -> (size, std430 alignment, slang, C++ element, C++ count)
TYPES = {
    "uint": (4, 4, "uint", "uint32_t", 1),
    "int": (4, 4, "int", "int32_t", 1),
    "float": (4, 4, "float", "float", 1),
    "uint2": (8, 8, "uint2", "uint32_t", 2),
    "int2": (8, 8, "int2", "int32_t", 2),
    "float2": (8, 8, "float2", "float", 2),
    "uint4": (16, 16, "uint4", "uint32_t", 4),
    "int4": (16, 16, "int4", "int32_t", 4),
    "float4": (16, 16, "float4", "float", 4),
    "float4x4": (64, 16, "column_major float4x4", "float", 16),
}
SCALARS = {"uint", "int", "float"}


class LayoutError(ValueError):
    pass


def identifier(name, what):
    if not name or not (name[0].isalpha() or name[0] == "_") or not all(c.isalnum() or c == "_" for c in name):
        raise LayoutError(f"{what} {name!r} is not an identifier")


def std430(fields):
    """[(name, type, offset)], size, alignment of a std430 struct."""
    offset, align, out = 0, 4, []
    for f in fields:
        t = f["type"]
        if t not in TYPES:
            hint = " (a 3-vector has no portable layout: use the 4-vector)" if t.endswith("3") else ""
            raise LayoutError(f"field {f['name']}: unknown type {t!r}{hint}")
        size, a = TYPES[t][0], TYPES[t][1]
        offset = (offset + a - 1) // a * a
        out.append((f["name"], t, offset))
        offset += size
        align = max(align, a)
    return out, (offset + align - 1) // align * align, align


def literal(t, v, lang):
    if t == "float":
        text = repr(float(v))
        return text + "f" if lang == "cpp" else text
    if t == "uint":
        if int(v) < 0:
            raise LayoutError(f"uint constant {v} is negative")
        return f"{int(v)}u"
    return str(int(v))


def validate(spec):
    names = set()
    for c in spec.get("constants", []):
        identifier(c["name"], "constant")
        if c["type"] not in SCALARS:
            raise LayoutError(f"constant {c['name']}: type {c['type']!r} is not a scalar")
        if c["name"] in names:
            raise LayoutError(f"{c['name']} is defined twice")
        names.add(c["name"])
    for s in spec.get("structs", []):
        identifier(s["name"], "struct")
        if s["name"] in names:
            raise LayoutError(f"{s['name']} is defined twice")
        names.add(s["name"])
        if not s.get("fields"):
            raise LayoutError(f"struct {s['name']} has no fields")
        seen = set()
        for f in s["fields"]:
            identifier(f["name"], "field")
            if f["name"] in seen:
                raise LayoutError(f"struct {s['name']}: field {f['name']} twice")
            seen.add(f["name"])
        std430(s["fields"])


def render_slang(spec):
    lines = [f"// {HEADER}", "// import shared.layout;", ""]
    for c in spec.get("constants", []):
        lines += [f"// {c['doc']}", f"static const {c['type']} {c['name']} = {literal(c['type'], c['value'], 'slang')};"]
    for s in spec.get("structs", []):
        lines += ["", f"// {s['doc']}", f"struct {s['name']}", "{"]
        for f in s["fields"]:
            lines.append(f"    {TYPES[f['type']][2]} {f['name']};   // {f.get('doc', '')}".rstrip())
        lines.append("};")
    return "\n".join(lines) + "\n"


def render_hpp(spec):
    lines = ["#pragma once", f"// {HEADER}", "// std430 layouts: every field offset and every size is asserted.",
             "#include <array>", "#include <cstddef>", "#include <cstdint>", "", "namespace ohao::gpu::shared {", ""]
    for c in spec.get("constants", []):
        cpp = TYPES[c["type"]][3]
        lines += [f"// {c['doc']}", f"inline constexpr {cpp} {c['name']} = {literal(c['type'], c['value'], 'cpp')};"]
    for s in spec.get("structs", []):
        fields, size, align = std430(s["fields"])
        lines += ["", f"// {s['doc']}", f"struct alignas({align}) {s['name']} {{"]
        for name, t, _ in fields:
            _, a, _, elem, count = TYPES[t]
            cpp = elem if count == 1 else f"std::array<{elem}, {count}>"
            lines.append(f"    alignas({a}) {cpp} {name}{{}};")
        lines.append("};")
        for name, _, off in fields:
            lines.append(f"static_assert(offsetof({s['name']}, {name}) == {off});")
        lines.append(f"static_assert(sizeof({s['name']}) == {size});")
    lines += ["", "} // namespace ohao::gpu::shared"]
    return "\n".join(lines) + "\n"


def outputs(spec):
    validate(spec)
    return {"slang": render_slang(spec), "hpp": render_hpp(spec)}


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__.splitlines()[1])
    p.add_argument("--check", action="store_true", help="exit 1 if a generated file is out of date")
    for k, v in DEFAULTS.items():
        p.add_argument(f"--{k}", default=v)
    a = p.parse_args(argv)
    try:
        with open(a.layout, encoding="utf-8") as f:
            spec = json.load(f)
        gen = outputs(spec)
    except (OSError, json.JSONDecodeError, LayoutError, KeyError) as e:
        print(f"gen_layout: {a.layout}: {e}", file=sys.stderr)
        return 2
    stale = []
    for k, text in gen.items():
        path = getattr(a, k)
        try:
            with open(path, encoding="utf-8", newline="") as f:
                current = f.read()
        except OSError:
            current = None
        if current == text:
            continue
        stale.append(path)
        if not a.check:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "w", encoding="utf-8", newline="\n") as f:
                f.write(text)
    if a.check and stale:
        print("gen_layout: out of date (run python tools/gen_layout.py): " + ", ".join(stale), file=sys.stderr)
        return 1
    if not a.check:
        print("gen_layout: " + (f"wrote {len(stale)} file(s)" if stale else "up to date"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
