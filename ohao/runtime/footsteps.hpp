#pragma once
// Footsteps (sub-project 6 spec, "Footsteps"): the window host plays the footsteps and landings
// the physics step logs (ecs::PhysicsEvent Footstep and Land) through AudioSystem, at the feet,
// heard from the world's camera, louder the faster the player moved. Headless hosts never make
// one: the events are what tests and agents read.
//
// Sounds are files named <surface>_<n>.wav (n a number), searched in a list of folders: the
// first folder holding any of a surface's sounds supplies all of them, in number order, played
// round robin; a surface without sounds plays "default"'s. The window host's folders are
// assets/local/audio/footsteps (git-ignored: sounds for local listening only, never committed)
// then assets/audio/footsteps (OHAO's own, generated by tools/audio/make_footsteps.py).
#include "audio/audio_system.hpp"
#include "ecs/world.hpp"

#include <cstddef>
#include <cstdint>
#include <filesystem>
#include <functional>
#include <map>
#include <memory>
#include <string>
#include <string_view>
#include <vector>

namespace ohao::runtime {

class FootstepSounds {
public:
    explicit FootstepSounds(const std::vector<std::filesystem::path>& folders);
    // The surface's next sound (default's when it has none); empty when there is none at all.
    [[nodiscard]] std::string next(std::string_view surface);
    [[nodiscard]] std::size_t sounds() const noexcept { return m_count; }

private:
    struct Set {
        std::vector<std::string> files;
        std::size_t next{0};
    };
    std::map<std::string, Set, std::less<>> m_sets;
    std::size_t m_count{0};
};

class Footsteps {
public:
    // The default audio device and the sounds under `root` (the project root). False when there
    // is no audio device; update then does nothing.
    bool initialize(const std::filesystem::path& root);
    // Plays what the physics scene logged since the last call (the first call starts at the log's
    // end). Call once per frame, after the frame's steps.
    void update(ecs::World& world);
    [[nodiscard]] uint64_t played() const noexcept { return m_played; }   // sounds started
    void setVolume(float volume) { m_audio.setMasterVolume(volume); }    // 0..1 (tests play silently)

private:
    AudioSystem m_audio;
    std::unique_ptr<FootstepSounds> m_sounds;
    uint64_t m_cursor{0};
    bool m_started{false};
    uint64_t m_played{0};
};

} // namespace ohao::runtime
