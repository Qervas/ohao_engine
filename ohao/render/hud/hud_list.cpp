int hudGlyph(char c) noexcept {
    if (c >= '0' && c <= '9') return c - '0';
    if (c >= 'a' && c <= 'z') c = static_cast<char>(c - 'a' + 'A');
    if (c >= 'A' && c <= 'Z') return 10 + (c - 'A');
    if (c == '/') return 36;
    if (c == '.') return 37;
    return -1;
}

std::span<const uint32_t> hudFontRows() noexcept { return kFont; }

uint32_t hudGlyphRow(int glyph, int row) noexcept {
    if (glyph < 0 || glyph >= kGlyphs || row < 0 || row >= kHudGlyphHeight) return 0;
    return kFont[static_cast<std::size_t>(glyph * kHudGlyphHeight + row)];
}

void hudRect(HudList& list, glm::vec4 rect, glm::vec4 color) {
    HudItem it;
    it.rect = rect;
    it.color = color;
    it.kind = static_cast<uint32_t>(HudKind::Rect);
    list.items.push_back(it);
}

void hudVignette(HudList& list, glm::vec4 rect, glm::vec4 color) {
    HudItem it;
    it.rect = rect;
    it.color = color;
    it.kind = static_cast<uint32_t>(HudKind::Vignette);
    list.items.push_back(it);
}

float hudTextWidth(std::string_view text, float px) noexcept {
    if (text.empty()) return 0.0f;
    return px * static_cast<float>(text.size() * (kHudGlyphWidth + 1) - 1);
}

float hudText(HudList& list, std::string_view text, glm::vec2 topLeft, float px, glm::vec4 color) {
    float x = topLeft.x;
    for (const char c : text) {
        const int g = hudGlyph(c);
        if (g >= 0) {
            HudItem it;
            it.rect = {x, topLeft.y, x + px * kHudGlyphWidth, topLeft.y + px * kHudGlyphHeight};
            it.color = color;
            it.kind = static_cast<uint32_t>(HudKind::Glyph);
            it.glyph = static_cast<uint32_t>(g);
            list.items.push_back(it);
        }
        x += px * (kHudGlyphWidth + 1);
    }
    return hudTextWidth(text, px);
}

